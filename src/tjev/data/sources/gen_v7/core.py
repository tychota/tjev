"""Shared machinery of the v7 generators: a *group* of rows built from one world.

A v7 base generator draws one world (its facts), renders it as tagged lines and returns a
:class:`Group`:

- ``a``: the state with its label, computed in code from the facts;
- ``b``: its contrastive twin, one fact changed by a minimal edit of one line (≤ 8 words)
  that flips the label;
- ``evidence``: the tags of the two lines the label needs. Removing either one makes the
  answer unknowable: the base's solver returns ``None`` on the facts the remaining lines
  state, and no surface form of the removed facts is left in the state or the question;
- ``unknown``: for each evidence tag, the target of the *unknowable twin* (``a`` without
  that line): the exact conditional base rate for noul, the abstain option for choice;
- ``aux``: auxiliary choice questions about ``a``'s state (an intermediate quantity:
  elapsed days, the order total, the overlap).

:func:`rows` turns a group into item dicts. Each row keeps a ``meta`` dict (base, group,
role, template family, licence, the tagged lines and the facts) for the tests and the
audits; the mix drops it (``tjev.data.item.parse_item`` keeps the item fields only), and
the group survives in the row id (``…-g<group>-<role>``).
"""

from __future__ import annotations

import difflib
import re
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

GENERATED = "Apache-2.0 (generated by tjev code)"
ROLES = ("a", "b", "unk", "aux")

# The abstain option of a choice question (JevBench's choice items use
# insufficient_information / cannot_determine). Keys are English, descriptions in the
# row's language. Pairs show it on half their rows, so it is never a cue by itself.
ABSTAIN = {
    "insufficient_information": {
        "en": "The information given is not enough to decide",
        "fr": "Les informations fournies ne permettent pas de trancher",
    },
    "cannot_determine": {
        "en": "Cannot be determined from the text",
        "fr": "Impossible à déterminer d'après le texte",
    },
}
# training rows offer insufficient_information, held-out rows cannot_determine (their own
# wording: the held-out split shares no template line with training)
ABSTAIN_KEY = {"train": "insufficient_information", "heldout": "cannot_determine"}
YES_NO = {"en": {"false": "No", "true": "Yes"}, "fr": {"false": "Non", "true": "Oui"}}


@dataclass(frozen=True)
class Line:
    """One line of a state. ``facts``: the names of the facts it states; ``surfaces``: the
    strings that state them (after its removal none of them may remain in the state)."""

    text: str
    tag: str = "filler"
    facts: tuple[str, ...] = ()
    surfaces: tuple[str, ...] = ()
    pre: str | None = None  # the separator before this line (None: the group's)


@dataclass
class Member:
    lines: list[Line]
    facts: dict[str, Any]
    expected: str | None = None
    target: dict[str, float] | None = None

    def state(self, drop: str | None = None, sep: str = "\n") -> str:
        kept = [line for line in self.lines if line.tag != drop]
        parts = [kept[0].text] + [
            (sep if line.pre is None else line.pre) + line.text for line in kept[1:]
        ]
        # a dropped sentence inside a paragraph leaves two spaces, or one before a newline
        return re.sub(r" +\n", "\n", re.sub(r"  +", " ", "".join(parts))).strip()

    def known(self, drop: str | None = None) -> dict[str, Any]:
        """The facts the lines state without the line tagged ``drop`` (and the context facts
        no line states, such as the language)."""
        carried = {f for line in self.lines for f in line.facts}
        names = {f for line in self.lines if line.tag != drop for f in line.facts}
        return {k: v for k, v in self.facts.items() if k in names or k not in carried}


@dataclass
class Group:
    base: str
    template: str
    lang: str
    question: dict
    a: Member
    b: Member | None
    evidence: tuple[str, str]
    unknown: dict[str, Any]  # evidence tag -> {"expected": label} | {"target": {...}}
    aux: list[dict] = field(default_factory=list)  # question dicts with "expected"
    license_use: str = GENERATED
    sep: str = "\n"
    extra: dict = field(default_factory=dict)


@dataclass(frozen=True)
class V7Source:
    bases: dict[str, float]  # base generator -> draw weight
    roles: tuple[str, ...]
    family: str  # the source's family (rows keep their base's family, see FAMILY)
    licence: tuple[str, str, str] = (GENERATED, "yes", "code-labelled v7 generators")
    note: str = ""
    row_family: dict[str, str] = field(default_factory=dict)  # role -> family override


def item(state: str, question: dict, expected=None, target=None) -> dict:
    row: dict[str, Any] = {"state": state, "question": question}
    if target is not None:
        row["target"] = target
    else:
        row["expected"] = expected
    return row


def with_abstain(criteria: dict, lang: str, key: str = "insufficient_information") -> dict:
    return {**criteria, key: ABSTAIN[key][lang]}


def abstain_key(criteria: dict) -> str | None:
    return next((k for k in ABSTAIN if k in criteria), None)


def _meta(g: Group, member: Member, role: str, drop: str | None = None, **more) -> dict:
    return {
        "base": g.base,
        "role": role,
        "template": g.template,
        "license_use": g.license_use,
        "evidence": list(g.evidence),
        "dropped": drop,
        "lines": [
            [line.tag, line.text, list(line.facts), list(line.surfaces), line.pre]
            for line in member.lines
        ],
        "facts": member.facts,
        **more,
    }


def rows(g: Group, roles=ROLES, twin_tag: str | None = None) -> list[dict]:
    """The group's rows for ``roles``. ``twin_tag``: the evidence line the unknowable twin
    drops (default: the first evidence tag)."""
    out = []
    q = g.question
    if "a" in roles:
        r = item(g.a.state(sep=g.sep), q, g.a.expected, g.a.target)
        r["meta"] = _meta(g, g.a, "a")
        out.append(r)
    if "b" in roles and g.b is not None:
        r = item(g.b.state(sep=g.sep), q, g.b.expected, g.b.target)
        r["meta"] = _meta(g, g.b, "b", edit=edited_lines(g.a, g.b))
        out.append(r)
    if "unk" in roles and g.unknown:
        tag = twin_tag or g.evidence[0]
        un = g.unknown[tag]
        uq = q
        if q["type"] == "choice" and abstain_key(q["criteria"]) is None:
            key = ABSTAIN_KEY["heldout" if ".heldout." in g.template else "train"]
            uq = {**q, "criteria": with_abstain(q["criteria"], g.lang, key)}
        r = item(g.a.state(drop=tag, sep=g.sep), uq, un.get("expected"), un.get("target"))
        r["meta"] = _meta(g, g.a, "unk", drop=tag)
        out.append(r)
    if "aux" in roles:
        for k, aq in enumerate(g.aux):
            question = {key: aq[key] for key in ("type", "instructions", "criteria")}
            r = item(g.a.state(sep=g.sep), question, aq["expected"])
            r["meta"] = _meta(g, g.a, "aux", aux=k, quantity=aq.get("quantity"))
            out.append(r)
    return out


# ---------------------------------------------------------------------------------------
# Checks (used by the tests and by generate_v7's assertions)

WORD = re.compile(r"\w+|[^\w\s]")


def edited_lines(a: Member, b: Member) -> list[str] | None:
    """The one line ``b`` changes (old, new), or None when the members differ elsewhere."""
    if len(a.lines) != len(b.lines):
        return None
    diff = [(x.text, y.text) for x, y in zip(a.lines, b.lines, strict=True) if x.text != y.text]
    return list(diff[0]) if len(diff) == 1 else None


def edit_words(old: str, new: str) -> int:
    """Words (tokens) inserted, deleted or replaced to turn ``old`` into ``new``."""
    x, y = WORD.findall(old), WORD.findall(new)
    n = 0
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(a=x, b=y, autojunk=False).get_opcodes():
        if op != "equal":
            n += max(i2 - i1, j2 - j1)
    if len(x) == len(y):  # substitutions in place ("10 h 45" -> "8 h 30"): difflib may align worse
        n = min(n, sum(a != b for a, b in zip(x, y, strict=True)))
    return n


def leaked(member: Member, drop: str, question: dict) -> list[str]:
    """Surface forms of the dropped line's facts still present elsewhere."""
    removed = next(line for line in member.lines if line.tag == drop)
    rest = member.state(drop=drop, sep="\n") + "\n" + question["instructions"]
    return [s for s in removed.surfaces
            if s and re.search(r"(?<!\w)" + re.escape(s) + r"(?!\w)", rest)]  # fmt: skip


def check_group(g: Group, solve: Callable[[dict], Any], max_edit: int = 8) -> None:
    """Raises AssertionError unless the group is a valid contrastive group."""
    assert g.a.expected is not None or g.a.target is not None
    assert solve(g.a.facts) == (g.a.expected or g.a.target), (g.base, g.template)
    for tag in g.evidence:
        assert sum(line.tag == tag for line in g.a.lines) == 1, (g.base, tag)
        assert solve(g.a.known(drop=tag)) is None, (g.base, tag, "still decidable")
        assert not leaked(g.a, tag, g.question), (g.base, tag, leaked(g.a, tag, g.question))
    if g.b is not None:
        edit = edited_lines(g.a, g.b)
        assert edit is not None, (g.base, "members differ in more than one line")
        assert edit_words(*edit) <= max_edit, (g.base, edit)
        assert solve(g.b.facts) == (g.b.expected or g.b.target)
        assert g.b.expected != g.a.expected, (g.base, "the edit does not flip the label")
