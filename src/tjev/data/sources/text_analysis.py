"""Text-analysis sources (docs/research/text_analysis.md, the mix's "analysis" block): authorship (human / AI, which model
family), formality, sentiment, emotion, offensiveness. EN + FR.

Same contract as ``sources.py``: each adapter maps one row to item dicts. Where several
annotators rated a text, the target is their distribution (soft), never its argmax.
Loading details (script-only repos, the 11.8 GB RAID CSV) were verified against the Hub
on 2026-09-29 with ``datasets`` 4.x, which no longer runs loading scripts.
"""

