EKMAN = {
    "anger": ("anger", "annoyance", "disapproval"),
    "disgust": ("disgust",),
    "fear": ("fear", "nervousness"),
    "joy": (
        "joy",
        "amusement",
        "approval",
        "excitement",
        "gratitude",
        "love",
        "optimism",
        "relief",
        "pride",
        "admiration",
        "desire",
        "caring",
    ),
    "sadness": ("sadness", "disappointment", "embarrassment", "grief", "remorse"),
    "surprise": ("surprise", "realization", "confusion", "curiosity"),
    "neutral": ("neutral",),
}
EKMAN_TEXT = {
    "anger": "Anger or annoyance",
    "disgust": "Disgust",
    "fear": "Fear or nervousness",
    "joy": "Joy, amusement, gratitude or affection",
    "sadness": "Sadness or disappointment",
    "surprise": "Surprise, confusion or curiosity",
    "neutral": "No particular emotion",
}


def go_emotions_raters(split: str):
    """One row per text: the Ekman distribution averaged over its raters (a rater who
    picks several emotions spreads their vote); unclear-flagged ratings are dropped."""
    from datasets import Dataset, load_dataset

    raw = load_dataset("google-research-datasets/go_emotions", "raw", split=split)
    columns = {g: [c for c in members if c in raw.column_names] for g, members in EKMAN.items()}
    votes: dict[str, np.ndarray] = defaultdict(lambda: np.zeros(len(EKMAN)))
    text: dict[str, str] = {}
    for row in raw:
        if row["example_very_unclear"]:
            continue
        hit = np.asarray([any(row[c] for c in columns[g]) for g in EKMAN], float)
        if hit.sum() == 0:
            continue
        votes[row["id"]] += hit / hit.sum()
        text[row["id"]] = row["text"]
    rows = [
        {"id": i, "text": text[i], "dist": (v / v.sum()).round(4).tolist(), "raters": v.sum()}
        for i, v in votes.items()
        if v.sum() >= 2  # a distribution needs at least two raters
    ]
    return Dataset.from_list(rows)


def go_emotions(row, rng, meta):
    dist = np.asarray(row["dist"], float)
    return [
        {
            "state": row["text"],
            "target": {g: float(p) for g, p in zip(EKMAN, dist / dist.sum(), strict=True)},
            "question": {
                "type": "choice",
                "instructions": "Which emotion does the author mainly express?",
                "criteria": EKMAN_TEXT,
            },
        }
    ]


OFFENSIVE_TEXT = {
    "en": (
        "Is this message offensive, abusive or hateful?",
        {"false": "Not offensive", "true": "Offensive, abusive or hateful"},
    ),
    "fr": (
        "Ce message est-il offensant, injurieux ou haineux ?",
        {"false": "Pas offensant", "true": "Offensant, injurieux ou haineux"},
    ),
}


def mlma(lang: str):
    """MLMA: ``sentiment`` joins the annotators' labels (``abusive_normal`` …); the share
    of non-``normal`` labels is the soft probability of "offensive"."""
    instructions, criteria = OFFENSIVE_TEXT[lang]

    def adapter(row, rng, meta):
        labels = [x for x in str(row["sentiment"]).split("_") if x]
        if not labels or not row["tweet"].strip():
            return []
        p = sum(x != "normal" for x in labels) / len(labels)
        text = re.sub(r"@user\b", "@utilisateur" if lang == "fr" else "@user", row["tweet"])
        return [
            {
                "state": text,
                "target": {"no": 1.0 - p, "yes": p},
                "question": {"type": "noul", "instructions": instructions, "criteria": criteria},
            }
        ]

    return adapter


def textdetox(lang: str):
    instructions, criteria = OFFENSIVE_TEXT[lang]

    def adapter(row, rng, meta):
        return [
            {
                "state": row["text"],
                "expected": "yes" if int(row["toxic"]) == 1 else "no",
                "question": {"type": "noul", "instructions": instructions, "criteria": criteria},
            }
        ]

    return adapter


